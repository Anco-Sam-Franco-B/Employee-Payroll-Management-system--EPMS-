import PDFDocument from "pdfkit";
import ExcelJS from "exceljs";
import { Parser } from "json2csv";
import fs from "fs";
import path from "path";

export const generateReportInPDF=async (req, res) => {
  const { department, status, fromDate, toDate } = req.body;

  // Filter logic
  let filtered = employees.filter((emp) => {
    return (
      (department === "All" || emp.dept === department) &&
      (status === "All" || emp.status === status)
    );
  });

  // Create PDF
  const doc = new PDFDocument();

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    "attachment; filename=epms-report.pdf"
  );

  doc.pipe(res);

  // Header
  doc.fontSize(20).text("EPMS REPORT", { align: "center" });
  doc.moveDown();

  doc.fontSize(12).text(`Department: ${department}`);
  doc.text(`Status: ${status}`);
  doc.text(`From: ${fromDate || "N/A"} To: ${toDate || "N/A"}`);

  doc.moveDown();

  // Table Header
  doc.fontSize(12).text("Employee Report", { underline: true });
  doc.moveDown();

  // Data
  filtered.forEach((emp, index) => {
    doc.text(
      `${index + 1}. ${emp.name} | ${emp.dept} | $${emp.salary} | ${emp.status}`
    );
  });

  doc.moveDown();
  doc.text("Generated by EPMS System", { align: "right" });

  doc.end();
};

export const generateAndSaveReport=async(req, res) => {
  const {
    title,
    type,
    department,
    employee,
    status,
    fromDate,
    toDate,
  } = req.body;

  const fileName = `report-${Date.now()}.pdf`;
  const filePath = path.join("reports", fileName);

  if (!fs.existsSync("reports")) {
    fs.mkdirSync("reports");
  }

  // Create PDF
  const doc = new PDFDocument();
  const stream = fs.createWriteStream(filePath);
  doc.pipe(stream);

  doc.fontSize(20).text("EPMS REPORT", { align: "center" });
  doc.moveDown();

  doc.fontSize(12).text(`Title: ${title}`);
  doc.text(`Type: ${type}`);
  doc.text(`Department: ${department}`);
  doc.text(`Employee: ${employee}`);
  doc.text(`Status: ${status}`);
  doc.text(`From: ${fromDate}`);
  doc.text(`To: ${toDate}`);

  doc.end();

  // Save into MySQL
  const sql = `
    INSERT INTO reports 
    (title, type, department, employee, status, from_date, to_date, file_name, file_path, generated_by)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `;

  db.query(
    sql,
    [
      title,
      type,
      department,
      employee,
      status,
      fromDate,
      toDate,
      fileName,
      filePath,
      "admin",
    ],
    (err, result) => {
      if (err) {
        console.error(err);
        return res.status(500).json({ error: "Database error" });
      }

      res.json({
        success: true,
        message: "Report generated and saved",
        reportId: result.insertId,
      });
    }
  );
}

