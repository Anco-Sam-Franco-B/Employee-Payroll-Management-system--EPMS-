export const downloadReport=async(req, res) => {
  const sql = "SELECT * FROM reports WHERE id = ?";

  db.query(sql, [req.params.id], (err, results) => {
    if (err) return res.status(500).json(err);

    if (results.length === 0) {
      return res.status(404).json({ error: "Report not found" });
    }

    const report = results[0];
    const filePath = path.resolve(report.file_path);

    res.download(filePath, report.file_name);
  });
}

export const multiSaveReport=async (req, res) => {
  try {
    const { title, type, format } = req.body;

    const fileName = `report-${Date.now()}.${format}`;
    const dir = "reports";

    if (!fs.existsSync(dir)) fs.mkdirSync(dir);

    const filePath = path.join(dir, fileName);

    // =========================
    // FILTER DATA (example)
    // =========================
    const data = employees;

    // =========================
    // PDF
    // =========================
    if (format === "pdf") {
      const doc = new PDFDocument();
      doc.pipe(fs.createWriteStream(filePath));

      doc.fontSize(20).text(title || "EPMS Report");
      doc.moveDown();

      data.forEach((e) => {
        doc.text(`${e.name} | ${e.dept} | $${e.salary} | ${e.status}`);
      });

      doc.end();
    }

    // =========================
    // EXCEL
    // =========================
    if (format === "excel") {
      const workbook = new ExcelJS.Workbook();
      const sheet = workbook.addWorksheet("Report");

      sheet.columns = [
        { header: "Name", key: "name" },
        { header: "Department", key: "dept" },
        { header: "Salary", key: "salary" },
        { header: "Status", key: "status" },
      ];

      sheet.addRows(data);

      await workbook.xlsx.writeFile(filePath);
    }

    // =========================
    // CSV
    // =========================
    if (format === "csv") {
      const parser = new Parser();
      const csv = parser.parse(data);
      fs.writeFileSync(filePath, csv);
    }

    // =========================
    // DOCX
    // =========================
    if (format === "docx") {
      const { Document, Packer, Paragraph, TextRun } = await import("docx");

      const doc = new Document({
        sections: [
          {
            children: [
              new Paragraph({
                children: [
                  new TextRun({
                    text: title || "EPMS Report",
                    bold: true,
                  }),
                ],
              }),

              ...data.map(
                (e) =>
                  new Paragraph(
                    `${e.name} | ${e.dept} | $${e.salary} | ${e.status}`
                  )
              ),
            ],
          },
        ],
      });

      const buffer = await Packer.toBuffer(doc);
      fs.writeFileSync(filePath, buffer);
    }

    // =========================
    // SAVE TO MYSQL
    // =========================
    const sql =
      "INSERT INTO reports (title, type, format, file_name, file_path) VALUES (?, ?, ?, ?, ?)";

    db.query(sql, [title, type, format, fileName, filePath]);

    res.json({
      success: true,
      message: "Report generated successfully",
      downloadUrl: `/api/reports/download/${fileName}`,
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ error: "Report generation failed" });
  }
}